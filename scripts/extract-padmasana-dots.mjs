/**
 * Sample the quote poster into a compact packed-dot grid.
 * Usage: node scripts/extract-padmasana-dots.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const POSTER = join(ROOT, 'public/media/quote-padmasana-poster.webp');
const OUT = join(ROOT, 'src/data/quotePadmasanaDots.ts');

const CREAM = { r: 245, g: 239, b: 231 };
const PITCH = 14;
const ORIGIN_X = 10.75;
const ORIGIN_Y = 4.5;
const COLS = 67;
const ROWS = 38;
const MIN_RADIUS = 0.6;
const RADIUS_SCALE = 36;

const { data, info } = await sharp(POSTER).ensureAlpha().raw().toBuffer({
  resolveWithObject: true,
});
const { width, height, channels } = info;

const inkAt = (x, y) => {
  const o = (y * width + x) * channels;
  return Math.max(
    0,
    (CREAM.r - data[o]) * 0.299 +
      (CREAM.g - data[o + 1]) * 0.587 +
      (CREAM.b - data[o + 2]) * 0.114,
  );
};

const measure = (cx, cy) => {
  const half = PITCH / 2 - 0.5;
  const x0 = Math.max(0, Math.floor(cx - half));
  const x1 = Math.min(width - 1, Math.ceil(cx + half));
  const y0 = Math.max(0, Math.floor(cy - half));
  const y1 = Math.min(height - 1, Math.ceil(cy + half));
  let inkSum = 0;
  let area = 0;
  let darkArea = 0;
  let r = 0;
  let g = 0;
  let b = 0;
  let nInk = 0;

  for (let y = y0; y <= y1; y += 1) {
    for (let x = x0; x <= x1; x += 1) {
      const dx = x + 0.5 - cx;
      const dy = y + 0.5 - cy;
      if (dx * dx + dy * dy > half * half) {
        continue;
      }
      const ink = inkAt(x, y);
      inkSum += ink;
      area += 1;
      if (ink > 12) {
        darkArea += 1;
        const o = (y * width + x) * channels;
        r += data[o];
        g += data[o + 1];
        b += data[o + 2];
        nInk += 1;
      }
    }
  }

  return {
    ink: area > 0 ? inkSum / area : 0,
    radius: darkArea > 0 ? Math.sqrt(darkArea / Math.PI) : 0,
    r: nInk ? r / nInk : CREAM.r,
    g: nInk ? g / nInk : CREAM.g,
    b: nInk ? b / nInk : CREAM.b,
  };
};

const dots = [];
for (let row = 0; row < ROWS; row += 1) {
  for (let col = 0; col < COLS; col += 1) {
    const sample = measure(ORIGIN_X + col * PITCH, ORIGIN_Y + row * PITCH);
    if (sample.radius <= MIN_RADIUS) {
      continue;
    }
    dots.push({
      col,
      row,
      radius: Math.min(255, Math.round(sample.radius * RADIUS_SCALE)),
      ink: Math.min(255, Math.round((sample.ink / 90) * 255)),
      r: Math.round(sample.r),
      g: Math.round(sample.g),
      b: Math.round(sample.b),
    });
  }
}

const packed = Buffer.alloc(dots.length * 7);
dots.forEach((dot, index) => {
  const offset = index * 7;
  packed[offset] = dot.col;
  packed[offset + 1] = dot.row;
  packed[offset + 2] = dot.radius;
  packed[offset + 3] = dot.ink;
  packed[offset + 4] = dot.r;
  packed[offset + 5] = dot.g;
  packed[offset + 6] = dot.b;
});

const figure = dots.filter((dot) => {
  const radiusPx = dot.radius / RADIUS_SCALE;
  const x = (ORIGIN_X + dot.col * PITCH) / width;
  return radiusPx >= 4 && x > 0.28 && x < 0.72;
});
const figureYs = figure.map((dot) => (ORIGIN_Y + dot.row * PITCH) / height);
const figureXs = figure.map((dot) => (ORIGIN_X + dot.col * PITCH) / width);
figureXs.sort((a, b) => a - b);
const figureTop = Math.min(...figureYs);
const figureBottom = Math.max(...figureYs);
const spineX = figureXs[Math.floor(figureXs.length / 2)];

const source = `/* Generated by scripts/extract-padmasana-dots.mjs — do not hand-edit. */
export const QUOTE_PADMASANA_DOT_PACK = {
  cols: ${COLS},
  rows: ${ROWS},
  srcW: ${width},
  srcH: ${height},
  originX: ${ORIGIN_X},
  originY: ${ORIGIN_Y},
  pitch: ${PITCH},
  radiusScale: ${RADIUS_SCALE},
  count: ${dots.length},
  figureTop: ${figureTop},
  figureBottom: ${figureBottom},
  spineX: ${spineX},
  packed: '${packed.toString('base64')}',
} as const;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, source);
console.log(
  JSON.stringify(
    {
      out: OUT,
      dots: dots.length,
      bytes: packed.length,
      fileBytes: Buffer.byteLength(source),
    },
    null,
    2,
  ),
);
